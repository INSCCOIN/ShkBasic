def main():
    out = []
    out.append("/* font6x8.h - 5x7 glyphs in a 6x8 cell, generated by tools/mkfont.py")
    out.append(" * Hand-authored for shkbasic; no external font dependency. */")
    out.append("#ifndef FONT6X8_H")
    out.append("#define FONT6X8_H")
    out.append("")
    out.append("#define FONT_W 6")
    out.append("#define FONT_H 8")
    out.append("#define FONT_FIRST 32")
    out.append("#define FONT_LAST 126")
    out.append("")
    out.append("static const unsigned char font6x8[FONT_LAST - FONT_FIRST + 1][8] = {")
    for code in range(32, 127):
        ch = chr(code)
        if ch not in G:
            print("missing glyph %r" % ch, file=sys.stderr)
            return 1
        rows = G[ch].split('|')
        if len(rows) != 8 or any(len(r) != 5 for r in rows):
            print("bad glyph %r: %d rows" % (ch, len(rows)), file=sys.stderr)
            return 1
        bytes_ = []
        for r in rows:
            b = 0
            for x, c in enumerate(r):
                if c == '#':
                    b |= 1 << (7 - x)
            bytes_.append(b)
        label = ch if ch not in ('*', '/', '\\') else {'*': 'star', '/': 'slash', '\\': 'backslash'}[ch]
        comment = "" if ch in ('*', '/') else "  /* %s */" % label
        out.append("  {%s},%s" % (",".join("0x%02X" % b for b in bytes_), comment))
    out.append("};")
    out.append("")
    out.append("#endif")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")

    # render a sample for visual verification
    for word in ("Hamburgefonstiv", "0123456789 {}[]", "Sharp#@%&*/\\|~"):
        for y in range(8):
            line = ""
            for ch in word:
                rows = G.get(ch, G[' ']).split('|')
                line += "".join('#' if c == '#' else '.' for c in rows[y]) + "."
            print(line)
        print()
    return 0

sys.exit(main())
